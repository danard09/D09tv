val LocalAppStrings = staticCompositionLocalOf { englishStrings() }

fun stringsForLanguage(language: AppLanguage): AppStrings = when (language) {
    AppLanguage.SORANI -> soraniStrings()
    AppLanguage.BADINI -> badiniStrings()
    AppLanguage.ARABIC -> arabicStrings()
    AppLanguage.ENGLISH -> englishStrings()
}

private fun translateGroupSorani(group: String): String = when (group.uppercase()) {
    "KURD TV" -> "کەناڵە کوردییەکان"
    "KURD SPORTS" -> "وەرزشی کوردی"
    "ALWAN SPORTS" -> "وەرزشی ئەلوان"
    "BEIN+" -> "بی ئین سپۆرتس+"
    "SPORTS" -> "وەرزش"
    "MUSIC" -> "میوزیک"
    "QURAN" -> "قورئانی پیرۆز"
    "KIDS" -> "منداڵان"
    "DOCUMENTARY" -> "بەڵگەنامەیی"
    else -> group
}

